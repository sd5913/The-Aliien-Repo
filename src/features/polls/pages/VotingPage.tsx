import { useLocale } from "../../../i18n/LocaleProvider";
import type { MessageKey } from "../../../i18n/catalog";
import { readDraft, saveDraft, clearDraft, isVoteDraft } from "../utils/drafts";
import { pollPath, pollReturnTo } from "../utils/navigation";
import { useParticipant } from "../../auth/utils/useParticipant";
import { useAccount } from "../../auth/components/AccountProvider";
import { useEffect, useRef, useState } from "react";
import { Link, Navigate, useLocation, useNavigate, useParams } from "react-router-dom";
import { PageShell } from "../../../components/layout/PageShell";
import { LoadingState } from "../../../components/ui/LoadingState";
import { StatusPill, isPollOpen } from "../../../components/ui/StatusPill";
import { Modal } from "../../../components/ui/Modal";
import { Toast } from "../../../components/ui/Toast";
import { usePolls } from "../hooks/usePolls";
import { OptionCarousel } from "../components/OptionCarousel";
import { getVoter, isPollOwner } from "../utils/voting";
import { optionColor } from "../utils/optionColors";
import pourSoundUrl from "../../../assets/audio/vote-pour.mp3";

export function VotingPage() {
  const { t, participants } = useLocale();
  const { id = "" } = useParams();
  const navigate = useNavigate();
  const location = useLocation();
  const returnTo = pollReturnTo(location);
  const { polls, loading, error, updatePoll } = usePolls({ pollId: id });
  const poll = polls.find((item) => item.id === id);
  const { user: accountUser, loading: accountLoading } = useAccount();
  const participant = useParticipant();
  const voter = participant ?? getVoter();
  const draftKey = `bothpls:draft:vote:${voter.id}:${id}`;
  const pendingDraftKey = `bothpls:draft:vote:pending:${id}`;
  const [hydratedKey, setHydratedKey] = useState("");
  const [saving, setSaving] = useState(false);
  const [draftNotice, setDraftNotice] = useState<MessageKey | "">("");
  const existingVote = poll?.votes.find((vote) => vote.voter.id === voter.id);
  // Match comments by voter identity: the vote row id is generated by Supabase
  // and changes, so a stored voteId never survives a reload.
  // 评论按投票者身份匹配：votes.id 由 Supabase 生成，刷新后必然对不上。
  const existingComment = poll?.comments.find((item) => item.voter.id === voter.id);
  const [activeId, setActiveId] = useState("");
  const [selectedId, setSelectedId] = useState("");
  const [pourSequence, setPourSequence] = useState(0);
  const pourAudio = useRef<HTMLAudioElement>(null);
  const [comment, setComment] = useState("");
  const [confirmCommentDelete, setConfirmCommentDelete] = useState(false);
  const [toast, setToast] = useState<MessageKey | "">("");
  const authRedirecting = useRef(false);
  const open = poll ? isPollOpen(poll) : false;
  // Seed the form once per poll, after the async fetch resolves.
  // 数据异步返回后才回填，每个投票只回填一次，避免覆盖正在编辑的内容。
  const hydratedPollId = useRef<string | null>(null);
  useEffect(() => {
    const audio = pourAudio.current;
    return () => audio?.pause();
  }, [id, loading, accountLoading, open]);
  useEffect(() => {
    if (!poll || accountLoading || hydratedPollId.current === `${poll.id}:${voter.id}`) return;
    hydratedPollId.current = `${poll.id}:${voter.id}`;
    const params = new URLSearchParams(location.search);
    const intent = params.get("pendingChoice");
    const pending = intent ? { activeId: intent, selectedId: intent, comment: "" } : readDraft(pendingDraftKey, isVoteDraft);
    if (intent && accountUser) {
      params.delete("pendingChoice");
      navigate(location.pathname + (params.size ? "?" + params.toString() : "") + location.hash, { replace: true, state: location.state });
    }
    const draft = pending ?? readDraft(draftKey, isVoteDraft);
    if (pending && accountUser && saveDraft(draftKey, pending)) clearDraft(pendingDraftKey);
    const savedOptionId = draft ? (poll.options.some((option) => option.id === draft.selectedId) ? draft.selectedId : "") : existingVote?.selectedOptionId ?? "";
    setActiveId(draft && poll.options.some((option) => option.id === draft.activeId) ? draft.activeId : savedOptionId);
    setSelectedId(savedOptionId);
    setComment(draft?.comment ?? existingComment?.text ?? "");
    setDraftNotice(draft ? "vote.restored" : "");
    setHydratedKey(draftKey);
  }, [poll, accountLoading, accountUser, voter.id, existingVote, existingComment, draftKey, pendingDraftKey, id, location, navigate]);

  useEffect(() => {
    if (hydratedKey !== draftKey) return;
    if (!saveDraft(draftKey, { activeId, selectedId, comment })) setDraftNotice("poll.draftUnavailable");
  }, [hydratedKey, draftKey, activeId, selectedId, comment]);

  if (accountLoading || loading) return <PageShell backTo="/" showNavigation={false}><LoadingState /></PageShell>;
  if (error) return <PageShell backTo={returnTo} showNavigation={false}><p className="settings-feedback" role="alert">{t("poll.loadFailed")}</p></PageShell>;
  if (!poll) return <PageShell backTo={returnTo} showNavigation={false}><div className="empty-state"><h2>{t("poll.missing")}</h2><p>{t("poll.missingDetails")}</p><Link className="purple-button" to="/">{t("common.home")}</Link></div></PageShell>;

  if (!open) return <Navigate replace to={pollPath(poll.id, "results", returnTo)} />;
  if (isPollOwner(poll, accountUser?.id ?? "")) return <Navigate replace to={pollPath(poll.id, "results", returnTo)} />;

  const activeIndex = Math.max(0, poll.options.findIndex((option) => option.id === activeId));
  const activeOption = poll.options[activeIndex];
  const letter = (index: number) => String.fromCharCode(65 + index);
  const selectedIndex = poll.options.findIndex((option) => option.id === selectedId);
  const selectedOption = selectedIndex >= 0 ? poll.options[selectedIndex] : undefined;
  const selectionColor = optionColor(selectedOption ?? activeOption, selectedOption ? selectedIndex : activeIndex);
  const redirectGuestToLogin = () => {
    if (accountUser || authRedirecting.current) return;
    if (!saveDraft(pendingDraftKey, { activeId, selectedId, comment })) {
      setDraftNotice("poll.draftUnavailable");
      return;
    }
    authRedirecting.current = true;
    const currentPath = location.pathname + location.search + location.hash;
    navigate("/auth?mode=login&returnTo=" + encodeURIComponent(currentPath));
  };
  const saveVote = async () => {
    if (saving) return;
    if (!accountUser) { redirectGuestToLogin(); return; }
    if (!isPollOpen(poll)) { navigate(pollPath(poll.id, "results", returnTo), { replace: true }); return; }
    if (!selectedId) { setToast("vote.chooseFirst"); return; }
    const now = new Date().toISOString();
    const voteId = existingVote?.id ?? crypto.randomUUID();
    try {
      setSaving(true);
      await updatePoll(poll.id, (current) => {
        const vote = { id: voteId, voter, selectedOptionId: selectedId, ranking: [selectedId], submittedAt: now };
        // Replace this voter's comment instead of filtering by a vote id that
        // the database regenerates; keeps exactly one comment per voter.
        // 按投票者身份替换评论，保证一人一条，重复提交不会留下旧评论。
        const comments = current.comments.filter((item) => item.voter.id !== voter.id);
        if (comment.trim()) comments.push({ id: crypto.randomUUID(), voter, text: comment.trim(), createdAt: now, optionId: selectedId });
        return { ...current, votes: [...current.votes.filter((item) => item.voter.id !== voter.id), vote], comments };
      });
      clearDraft(draftKey);
      navigate(pollPath(poll.id, "results", returnTo));
    } catch (error) {
      console.error("Could not save vote.", error);
      if (error instanceof Error && /POLL_CLOSED|投票已结束|INVALID_DEADLINE/.test(error.message)) {
        setToast("vote.closed");
      } else setToast("vote.saveFailed");
    } finally { setSaving(false); }
  };

  const submitVote = async () => {
    if (!selectedId) { setToast("vote.chooseFirst"); return; }
    if (existingComment && !comment.trim()) {
      setConfirmCommentDelete(true);
      return;
    }
    await saveVote();
  };

  return (
    <PageShell showNavigation={false} backTo={returnTo} title={t("vote.help")}>
      <div className="voting-title"><div className="voting-meta"><StatusPill poll={poll} /><span>{participants(poll.votes.length)}</span></div><h1>{poll.title}</h1>{poll.description && <p>{poll.description}</p>}</div>
      {!open && <div className="notice-banner">{t("vote.closed")}</div>}
      {draftNotice && <p className="field-hint" role="status">{t(draftNotice)}</p>}
      <OptionCarousel options={poll.options} activeId={activeId} onBrowse={(nextId) => {
        setActiveId(nextId);
        if (nextId !== activeOption?.id) {
          pourAudio.current?.pause();
          setSelectedId("");
          setPourSequence(0);
        }
      }} />
      <section className="vote-cup-card">
        <audio key={id} ref={pourAudio} src={pourSoundUrl} preload="auto" />
        <button className="vote-cup-confirm" disabled={saving || !open || !activeOption} onClick={() => {
          if (!accountUser) {
            const saved = saveDraft("bothpls:draft:vote:pending:" + id, { activeId: activeOption.id, selectedId: activeOption.id, comment });
            const params = new URLSearchParams(location.search);
            if (!saved) params.set("pendingChoice", activeOption.id);
            const target = location.pathname + (params.size ? "?" + params.toString() : "") + location.hash;
            navigate("/auth?mode=login&returnTo=" + encodeURIComponent(target));
            return;
          }
          setSelectedId(activeOption?.id ?? "");
          setPourSequence((sequence) => sequence + 1);
          const audio = pourAudio.current;
          if (audio) {
            audio.currentTime = 0;
            void audio.play().catch(() => { /* Voting still works if playback is blocked. */ });
          }
        }} aria-pressed={selectedId === activeOption?.id} aria-label={t("vote.selectAria", { letter: letter(activeIndex), name: activeOption?.name ?? "" })}>
          {selectedId === activeOption?.id ? t("vote.selected", { letter: letter(activeIndex) }) : t("vote.select", { letter: letter(activeIndex) })}
        </button>
        <div className="vote-cup-choice">
          <svg className="vote-cup-art" viewBox="0 0 260 245" aria-hidden="true">
            <rect x="91" y="8" width="78" height="12" rx="6" fill="#cdb5e6a6" />
            <rect x="112" y="19" width="36" height="19" rx="6" fill="#b59bd5" />
            <rect x="121" y="33" width="18" height="11" rx="4" fill="#cdb5e6" />
            <rect x="49" y="62" width="162" height="174" rx="26" fill="#ffffff35" stroke="#ffffffdd" strokeWidth="5" />
            <rect x="42" y="56" width="176" height="12" rx="6" fill="#ffffffb3" stroke="#ffffffdd" strokeWidth="2" />
            {selectedOption && <g key={pourSequence} className={pourSequence > 0 ? "vote-cup-pouring" : undefined}>
              <path className="vote-cup-liquid" d="M58 143Q58 133 68 133H192Q202 133 202 143V208Q202 227 183 227H77Q58 227 58 208Z" fill={selectionColor} />
              {pourSequence > 0 && <g fill={selectionColor}>
                <path className="vote-cup-drop" d="M130 43c-2 7-6 11-6 15a6 6 0 0 0 12 0c0-4-4-8-6-15Z" />
                <path className="vote-cup-stream" d="M130 34V211" fill="none" stroke={selectionColor} strokeWidth="9" strokeLinecap="round" />
                <circle className="vote-cup-splash vote-cup-splash-left" cx="124" cy="130" r="4" />
                <circle className="vote-cup-splash vote-cup-splash-right" cx="136" cy="130" r="3" />
                <ellipse className="vote-cup-ripple" cx="130" cy="130" rx="22" ry="5" fill="none" stroke="#ffffffb3" strokeWidth="2" />
              </g>}
            </g>}
          </svg>
          <span className="vote-cup-label" aria-live="polite">{selectedOption ? t("vote.picked", { letter: letter(selectedIndex) }) : t("vote.select", { letter: letter(activeIndex) })}</span>
        </div>
      </section>
      <label className="field-label comment-input-label" htmlFor="vote-comment">{t("vote.leaveComment")} <span className="optional">{t("common.optional")}</span></label>
      <textarea id="vote-comment" className="text-input textarea vote-comment-input" value={comment} readOnly={!accountUser} onFocus={redirectGuestToLogin} onClick={redirectGuestToLogin} onChange={(event) => setComment(event.target.value)} placeholder={t("vote.commentHint")} rows={2} maxLength={200} />
      {existingVote && open && <p className="field-hint">{t("vote.alreadyVoted")}</p>}
      <button className="purple-button button-full vote-cup-submit" disabled={saving || !open || (Boolean(accountUser) && !selectedId)} onClick={() => {
        if (!accountUser) redirectGuestToLogin();
        else void submitVote();
      }}>{t(saving ? "vote.submitting" : existingVote ? "vote.update" : "vote.submit")}</button>
      <p className="vote-cup-note">{t("vote.editable")}</p>
      {confirmCommentDelete && <Modal title={t("comment.deleteQuestion")} onClose={() => setConfirmCommentDelete(false)} actions={<><button className="button-soft" onClick={() => setConfirmCommentDelete(false)}>{t("common.cancel")}</button><button className="danger-button" onClick={() => { setConfirmCommentDelete(false); void saveVote(); }}>{t("vote.deleteAndSubmit")}</button></>}><p>{t("vote.deleteDetails")}</p></Modal>}
      {toast && <Toast message={t(toast)} onClose={() => setToast("")} />}
    </PageShell>
  );
}
